"""Chance of a catch per attempt, for each method and target speed, from out/compare_methods.csv.
Run: python analysis/tactics/compare_eval.py   (a few seconds) -> RESULTS.md

Aiming error: random, normal, sigma per axis (0.25 m ~ automatic aiming, 0.5 m ~ manual piloting),
around the best aim point for that method and speed (so 'aim slightly ahead' is included).
  strict catch = 12+ net points touching AND the net spread over at least a 60 deg patch of the target
                 (R_min <= 0.75); a bundle of line landing on it does not count
  loose catch  = 12+ net points touching
"""
import sys
from math import erf, sqrt
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from methods import VARIANTS, GROUPS, SPEEDS, STEP, read_rows  # noqa: E402

CSV = HERE / "out" / "compare_methods.csv"
R_MAX = 0.75
SIGMAS = (0.25, 0.5)
H = STEP / 2
_Phi = np.vectorize(lambda x: 0.5 * (1 + erf(x / sqrt(2))))


def _grids(by, name, u):
    _, _, centre, A, C = VARIANTS[name]
    na, nc = len(A), len(C)
    G = {k: np.zeros((na, nc)) for k in ("loose", "strict", "props")}
    G["t"] = np.full((na, nc), np.nan)
    G["pull"] = np.zeros((na, nc))
    avals = centre(u) + A
    for (_, _, ia, ic, a, c, ok, tc, cl, pu, nodes, Rm, op) in by[(name, u)]:
        strict = bool(ok and Rm is not None and Rm <= R_MAX)
        G["loose"][ia, ic] = ok
        G["strict"][ia, ic] = strict
        G["props"][ia, ic] = cl < 0
        G["t"][ia, ic] = tc if strict else np.nan
        G["pull"][ia, ic] = pu
    cfull = np.concatenate([-C[:0:-1], C])
    mirror = lambda g: np.concatenate([g[:, :0:-1], g], axis=1)  # noqa: E731
    return avals, cfull, {k: mirror(v) for k, v in G.items()}


def _evaluate(by, name, u, sigma, rule):
    avals, cvals, G = _grids(by, name, u)
    wc = _Phi((cvals + H) / sigma) - _Phi((cvals - H) / sigma)
    best = None
    for ca in np.linspace(avals[0], avals[-1], 241):
        wa = _Phi((avals + H - ca) / sigma) - _Phi((avals - H - ca) / sigma)
        w = np.outer(wa, wc)
        p = float((w * G[rule]).sum())
        if best is None or p > best[0] + 1e-12:
            best = (p, ca, w)
    p, ca, w = best
    ws = w * G["strict"]
    g = G[rule]
    return dict(p=p, aim=ca, variant=name,
                t=float(np.nansum(ws * G["t"]) / ws.sum()) if ws.sum() > 0 else None,
                p_props=float((w * G["props"]).sum()),
                pull=float((ws * G["pull"]).sum() / ws.sum()) if ws.sum() > 0 else 0.0,
                zone=float(g.sum() * STEP * STEP),
                edge=bool(g[0, :].any() or g[-1, :].any() or g[:, 0].any() or g[:, -1].any()))


def evaluate_all(csv_path=CSV):
    """{(rule, sigma, method, speed): result of the best variant}"""
    by = {}
    for r in read_rows(csv_path):
        by.setdefault((r[0], r[1]), []).append(r)
    out = {}
    for rule in ("strict", "loose"):
        for sigma in SIGMAS:
            for g, names in GROUPS.items():
                for u in SPEEDS:
                    out[(rule, sigma, g, u)] = max((_evaluate(by, nm, u, sigma, rule) for nm in names), key=lambda e: e["p"])
    return out


def main():
    ev = evaluate_all()
    L = ["# Capture method comparison", "",
         "Generated by `compare_eval.py` from `out/compare_methods.csv` (made by `compare_methods.py`).", "",
         "Same simulated target for every method (0.25 m drone with its rotor downwash); the interceptor flies "
         "along with it at the target speed. Each cell is the chance of a catch in one attempt with a random "
         "aiming error (normal, per axis) around the best aim point.", "",
         "- **strict**: 12+ net points touching and the net spread over at least a 60° patch of the target",
         "- **loose**: 12+ net points touching (a bundle of line landing on the target also counts)", ""]
    for rule in ("strict", "loose"):
        for sigma in SIGMAS:
            L += [f"## {rule} rule, aiming error ±{sigma} m", "",
                  "| method | " + " | ".join(f"{u:.0f} m/s ({u * 3.6:.0f} km/h)" for u in SPEEDS) + " |",
                  "|---|" + "---|" * len(SPEEDS)]
            for g in GROUPS:
                L.append(f"| {g} | " + " | ".join(f"{ev[(rule, sigma, g, u)]['p'] * 100:.0f}%" for u in SPEEDS) + " |")
            L.append("")
    L += ["## Details (strict rule, ±0.25 m)", "",
          "| method | speed (m/s) | best variant | aim offset (m) | time to catch (s) | net in own props | tether pull (N) | catch zone (m²) |",
          "|---|---|---|---|---|---|---|---|"]
    for g in GROUPS:
        for u in SPEEDS:
            e = ev[("strict", 0.25, g, u)]
            t = f"{e['t']:.2f}" if e["t"] else "-"
            L.append(f"| {g} | {u:.0f} | {e['variant']} | {e['aim']:+.2f} | {t} | {e['p_props'] * 100:.0f}% | "
                     f"{e['pull']:.0f} | {e['zone']:.2f}{' (grid edge)' if e['edge'] else ''} |")
    L += ["", "Aim offset: along the flight path for down-firing and drape (positive = ahead of the target / later "
          "release), height above the target for forward-firing. Catch zone: area of aim offsets that catch. "
          "'grid edge' means the zone reaches the edge of the swept grid, so the true chance may be slightly higher.", ""]
    (HERE / "RESULTS.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
