"""Ideas for a better launcher, compared at the same energy with the same amount of net.
Run: python analysis/turret/launch_variants.py     (~4 min on 4 cores)  -> VARIANTS.md

Every variant throws 4 m2 of net (11 g, 0.15 m mesh) with 80 g of weights at 30 m/s (36 J), fired 20 deg upward:
  - more weights (5 or 6 instead of 4, on a net cut to match)
  - 'spiral': each barrel also angled sideways around the axis
  - pushing the folded net out of the cup as well, instead of leaving the weights to drag it out from rest
"""
import math
import sys
from multiprocessing import Pool
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from netlab import launch  # noqa: E402

AX = (math.cos(math.radians(20.0)), 0.0, math.sin(math.radians(20.0)))
E1 = np.array([0.0, 1.0, 0.0])
E2 = np.cross(np.array(AX), E1)
RANGES = [3, 4, 5, 6, 7, 8]
OFFS = np.round(np.arange(1, 12) * 0.15, 2)
AZIMUTHS = (0.0, 30.0, 60.0)      # the miss is tried in several directions; a square net reaches further toward its corners
V_PUSH = 26.0
VARIANTS = {
    "4 weights (as now)": dict(),
    "5 weights": dict(n_weights=5),
    "6 weights": dict(n_weights=6),
    "5 weights, spiral 45°": dict(n_weights=5, skew=45.0),
    "4 weights, spiral 45°": dict(skew=45.0),
    "4 weights, net pushed out, barrels at 24°": dict(v_net=V_PUSH, theta=24.0),
    "5 weights, net pushed out, barrels at 24°": dict(n_weights=5, v_net=V_PUSH, theta=24.0),
}


def job(a):
    name, R, ic, az = a
    kw = VARIANTS[name]
    if R is None:
        r = launch(axis=AX, t_end=1.2, n_rec=400, **kw)
        ok = r["open"] >= 0.5
        grow = np.maximum.accumulate(r["x"])
        return name, None, dict(max_open=float(r["open"].max()), band=(float(r["x"][ok][0]), float(r["x"][ok][-1])) if ok.any() else None,
                                t5=float(np.interp(5.0, grow, r["t"])), twist=float(abs(r["twist"][np.argmax(r["open"])])),
                                peak=r["peak_tension"])
    off = float(OFFS[ic]) * (math.cos(math.radians(az)) * E1 + math.sin(math.radians(az)) * E2)
    r = launch(axis=AX, start=tuple(-R * np.array(AX) + off), target_r=0.25, t_end=1.2, seed=1 + ic, **kw)
    return name, (R, ic, az), r["caught"]


if __name__ == "__main__":
    jobs = [(nm, None, 0, 0.0) for nm in VARIANTS] + [(nm, R, ic, az) for nm in VARIANTS for R in RANGES
                                                      for ic in range(len(OFFS)) for az in AZIMUTHS]
    with Pool(4) as p:
        res = p.map(job, jobs, chunksize=3)
    free = {nm: v for nm, key, v in res if key is None}
    hits = {(nm,) + key for nm, key, v in res if key is not None and v}
    L = ["# Launcher variants", "",
         "Generated by `launch_variants.py`. Every variant throws the same 4 m² of net with the same 80 g of weights at 30 m/s "
         "(36 J), fired 20° upward. 'Catch half-width' is how far off the aim line a hovering 0.25 m drone can be and still "
         "be caught. It is tried in three directions around the aim line and the worst is shown, because a net reaches "
         "further toward its corners than toward the middle of its sides.", "",
         "| variant | net opens to | time to 5 m | net turned by | catch half-width, worst direction, at " + " / ".join(f"{R}" for R in RANGES)
         + " m | average over 4-7 m, all directions |", "|---|---|---|---|---|---|"]
    for nm in VARIANTS:
        worst, allv = [], []
        for R in RANGES:
            per = []
            for az in AZIMUTHS:
                w = 0.075
                for ic in range(len(OFFS)):
                    if (nm, R, ic, az) in hits:
                        w = float(OFFS[ic]) + 0.075
                    else:
                        break
                per.append(w)
            worst.append(min(per))
            if 4 <= R <= 7:
                allv += per
        f = free[nm]
        L.append(f"| {nm} | {f['max_open'] * 100:.0f} % | {f['t5']:.2f} s | {f['twist']:.0f}° | " + " / ".join(f"{w:.2f}" for w in worst)
                 + f" | {np.mean(allv):.2f} m |")
    L += ["", "Pushing the net out costs about 4 J more (the 11 g net leaving at 26 m/s), on top of the 36 J in the weights. "
          "The model has no friction between the net and the cup and no line-on-line contact, so it cannot show a net "
          "tangling; a twisted launch is where that would matter most.", ""]
    (HERE / "VARIANTS.md").write_text("\n".join(L))
    print("\n".join(L))
